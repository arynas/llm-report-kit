"""Command-line workflow for the frozen public news snapshot."""
import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

from slmcp.config import Config, DataSource, Model, build_adapter
from slmcp.report import build_report_inputs

from .report import build_report, query_period
from .snapshot import SNAPSHOT, SOURCE_URL, fetch_snapshot, snapshot_paths
from .verify import audit


def make_inputs(data_dir, keyword, start, end):
    config = Config(DataSource("jsonl", paths=snapshot_paths(data_dir), sentiment_labels="model"),
                    Model("https://example.invalid", "offline"), today="2026-10-15")
    inputs = build_report_inputs(build_adapter(config), config, keyword, start, end, snapshot=SNAPSHOT)
    return {"request": {"keyword": keyword, "start": start, "end": end}, **inputs}


def write_json(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def write_outline(inputs, folder, source_name="GDELT Project", source_url=SOURCE_URL):
    query, facts = inputs["query"], inputs["facts"]
    titles = [section["title"] for section in inputs["outline"]]
    if inputs["data_available"] and not facts["peak"]:
        titles.insert(2, "No matching headlines")
    lines = [f"# {query['keyword'].title()} report outline", "", f"{query_period(query)} · `{query['snapshot']}`", ""]
    lines.extend(f"{i}. {title}" for i, title in enumerate(titles, 1))
    if inputs["data_available"]:
        lines.extend(("", f"Headlines in the requested period: **{facts['total']:,}**."))
        if facts["peak"]:
            lines.append(f"Peak: **{facts['peak']['count']:,}** on **{facts['peak']['at']}**.")
    else:
        lines.extend(("", "The snapshot does not cover the requested dates. This report has one slide about coverage."))
    lines.extend(("", "## Data notes", ""))
    lines.extend(f"- {warning}" for warning in inputs["warnings"])
    lines.extend(("", f"Data from the [{source_name}]({source_url}).", ""))
    (folder / "outline.md").write_text("\n".join(lines), encoding="utf-8")
    write_json(folder / "report-inputs.json", inputs)


def export_pdf(deck, folder, work):
    office = shutil.which("soffice") or shutil.which("libreoffice")
    mac_office = Path("/Applications/LibreOffice.app/Contents/MacOS/soffice")
    if office is None and mac_office.is_file():
        office = str(mac_office)
    if office is None:
        raise ValueError("LibreOffice is required. Install it and make soffice available on PATH.")
    profile = (work / "office-profile").as_uri()
    process = subprocess.run(
        [office, f"-env:UserInstallation={profile}", "--headless", "--convert-to", "pdf",
         "--outdir", str(folder), str(deck)], check=False, capture_output=True, text=True, timeout=120,
    )
    pdf = folder / "report.pdf"
    if process.returncode or not pdf.is_file():
        details = (process.stderr or process.stdout).strip()
        raise ValueError(f"LibreOffice failed to export report.pdf. {details}")
    return pdf


def build(args, folder, work):
    approved = json.loads(args.inputs.read_text(encoding="utf-8"))
    if not isinstance(approved, dict) or not isinstance(approved.get("request"), dict):
        raise ValueError("Pass the report-inputs.json generated by outline.")
    request = approved["request"]
    if set(request) != {"keyword", "start", "end"} or not all(isinstance(v, str) for v in request.values()):
        raise ValueError("Invalid outline request. Regenerate the outline.")
    inputs = make_inputs(args.data_dir, **request)
    if approved != inputs:
        raise ValueError("The saved inputs differ from the verified snapshot. Regenerate the outline and review it.")
    result = render_checked_report(inputs, folder, work)
    print(f"Checked {result['expected']['slides']} slide(s). No findings.")


def render_checked_report(inputs, folder, work, source_name="GDELT Project", source_url=SOURCE_URL):
    deck = folder / "report.pptx"
    build_report(inputs, deck, source_name, source_url)
    pdf = export_pdf(deck, folder, work)
    result = audit(inputs, deck, pdf, source_url)
    if result["status"] != "pass":
        findings = "\n".join(f"{i['artifact']} slide {i['page']}: {i['message']}" for i in result["issues"])
        raise ValueError(f"Report checks failed.\n{findings}")
    write_outline(inputs, folder, source_name, source_url)
    write_json(folder / "check_report.json", result)
    return result


def check_existing(args):
    out = args.out.resolve()
    if out in {path.resolve() for path in (args.inputs, args.pptx, args.pdf)}:
        raise ValueError("Choose a check report path separate from the inputs and slides.")
    inputs = json.loads(args.inputs.read_text(encoding="utf-8"))
    result = audit(inputs, args.pptx, args.pdf, SOURCE_URL)
    write_json(out, result)
    print(f"Report check {result['status']}. Findings: {len(result['issues'])}.")
    return 0 if result["status"] == "pass" else 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    fetch = commands.add_parser("fetch-data", help="download and verify the public snapshot")
    outline = commands.add_parser("outline", help="prepare the report outline and its facts")
    render = commands.add_parser("build", help="render the reviewed outline and check both files")
    check = commands.add_parser("check", help="check an existing report against its verified facts")
    for name in ("inputs", "pptx", "pdf", "out"):
        check.add_argument(f"--{name}", type=Path, required=True)
    for command in (fetch, outline, render):
        command.add_argument("--data-dir", type=Path, default=Path("data"))
    for command in (outline, render):
        command.add_argument("--out", type=Path, required=True, help="path for a new output directory")
    outline.add_argument("--keyword", required=True)
    outline.add_argument("--start", required=True, help="first WIB date (YYYY-MM-DD)")
    outline.add_argument("--end", required=True, help="last WIB date (YYYY-MM-DD)")
    render.add_argument("--inputs", type=Path, required=True, help="reviewed report-inputs.json")
    args = parser.parse_args(argv)
    try:
        if args.command == "fetch-data":
            fetch_snapshot(args.data_dir)
            return 0
        if args.command == "check":
            return check_existing(args)
        out = args.out.resolve()
        if out.exists():
            raise ValueError(f"Output already exists: {out}. Choose a new directory.")
        out.parent.mkdir(parents=True, exist_ok=True)
        with TemporaryDirectory(prefix=".report-", dir=out.parent) as temp:
            work = Path(temp)
            folder = work / "output"
            folder.mkdir()
            if args.command == "outline":
                write_outline(make_inputs(args.data_dir, args.keyword, args.start, args.end), folder)
            else:
                build(args, folder, work)
            folder.rename(out)
        print(out)
        return 0
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        print(f"llm-report-kit: {error}", file=sys.stderr)
        return 1
